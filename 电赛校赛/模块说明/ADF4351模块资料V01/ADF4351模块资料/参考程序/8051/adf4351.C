#include "adf4351.h"
#include "delay.h"
//-----------------------------------------------------------------
// 初始化程序区
//-----------------------------------------------------------------
// 变量申明
//-----------------------------------------------------------------
ulint R=125; // R为参考分配器的数值，计算公式：输入频率/（2*R）=0.1  
		     // 注：输入频率的单位为MHz，R的范围为0~1023的整数
			 // 默认输入频率为板载25M晶振，故得R为125。
//-----------------------------------------------------------------
// ADF4351_Init(ulint cf)
//-----------------------------------------------------------------
//
// 函数功能: adf4351初始化
// 入口参数: ulint date   //初始输出频率为35Mhz
// 返回参数: 无
// 全局变量: 无   
// 注意事项: 
//  
//-----------------------------------------------------------------
void ADF4351_Init(ulint date)
{
	ADF_CE = 1;
	delay_us(5);
	ADF_CLK = 0;
	ADF_LE = 1;
	ADF_DATA = 0;	
	ADF4351_Wdata(0x00580005);	 // 设置寄存器5 ：LD设置为数字锁定监测模式
	ADF4351_Wdata(0x0060a43c);	 // 设置寄存器4 : 差分输出功率设置为5dbm，使能静音至检测到锁定，频段选择时钟设为10K 
	ADF4351_Wdata(0x006004b3);	 // 设置寄存器3	：charge cancellation，ABP设为1
    ADF4351_Wdata(0x0D003Fc2| R<<14);	 // 设置寄存器2：电荷泵电流设为5mA，LDP,LDF设为1。
	ADF4351_Wdata(0x08008011);			 //	设置寄存器1 ：预分配器设为8/9，使能输出分频
	ADF4351_Wdata(0x00000000|date<<15);	 // N分配器数据写入寄存器R0 

}
//-----------------------------------------------------------------
// 功能程序区
//-----------------------------------------------------------------


//-----------------------------------------------------------------
// ADF4351_Wdata(ulint dat)
//-----------------------------------------------------------------
//
// 函数功能: 写数据到adf4351
// 入口参数: 无
// 返回参数: 无
// 全局变量: 无   
// 注意事项: 
//     
//-----------------------------------------------------------------
void ADF4351_Wdata(ulint dat)
{
	uchar i;
	ADF_CLK = 0;
	ADF_LE = 0;
	for(i=0; i<32; i++)
	{
		if( dat & 0x80000000 )
			ADF_DATA = 1;
		else
			ADF_DATA = 0;	
		dat <<= 1;		
		ADF_CLK = 1;
		ADF_CLK = 0;	
	}
	ADF_LE = 1;	
}
